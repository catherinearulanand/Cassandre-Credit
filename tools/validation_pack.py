"""Assemble the independent-validation pack (P3-11) from the repository's own evidence.

    python -m tools.validation_pack [out.md]

The pack is a hand-over for the bank's model-risk validators: what each model or agent is, which
evidence exists, what the gates say and which audit findings are still open. It reads the reports and
the inventory; it never states a number that is not in them, and an entry without evidence says so.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def _load_json(rel: str) -> dict | None:  # type: ignore[type-arg]
    p = ROOT / rel
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _open_findings() -> list[str]:
    text = (ROOT / "docs" / "AUDIT_LOG.md").read_text(encoding="utf-8")
    out = []
    for line in text.splitlines():
        if line.startswith("|") and re.search(r"\*\*(Open|open)\b|partly open|\*\*Open", line):
            cells = [c.strip() for c in line.strip("|").split("|")]
            out.append(f"{cells[0]}: {cells[2] if len(cells) > 2 else ''}")
    return out


def build() -> str:
    inv = yaml.safe_load((ROOT / "governance" / "ai_inventory.yaml").read_text(encoding="utf-8"))
    ocr = _load_json("reports/ocr_accuracy.json")
    sim = _load_json("reports/simulation_report.json")
    lines = [
        "# Independent validation pack",
        "",
        "Generated by `python -m tools.validation_pack`. Do not edit by hand.",
        "",
    ]
    lines += [
        "## Inventory",
        "",
        "| Id | Kind | Tier | Owner | Validation status | Evidence | Card |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in inv["entries"]:
        ev = e.get("evidence", "none")
        if ev != "none" and not (ROOT / ev).exists():
            ev = f"{ev} (MISSING)"
        lines.append(
            f"| {e['id']} | {e['kind']} | {e['risk_tier']} | {e['owner']} | {e['validation_status']} | {ev} | {e.get('card', '')} |"
        )
    lines += ["", "## Evidence headlines", ""]
    if ocr:
        o = ocr["overall"]
        lines += [
            f"- OCR (development engine, synthetic): {o['stp_precision']['n']} straight-through figures, "
            f"precision {o['stp_precision']['value']:.4f} (CI {o['stp_precision']['ci_low']:.4f} to "
            f"{o['stp_precision']['ci_high']:.4f}); straight-through rate {o['stp_rate']['value']:.3f}; "
            f"accuracy {o['accuracy_after_validation']['value']:.3f}. Release gate status is in `docs/OCR_ACCURACY.md`."
        ]
    else:
        lines.append("- OCR: no report found.")
    if sim:
        e = sim["models"]["ews"]["metrics"]
        b = sim["models"]["breach_forecast"]
        lines += [
            f"- EWS AUC {e['auc']:.3f} (CI {e['auc_ci95_bootstrap'][0]:.3f} to {e['auc_ci95_bootstrap'][1]:.3f}) "
            f"against a rules-only baseline of {sim['models']['ews']['baselines']['rules_only_indicator_count_auc']:.3f}.",
            f"- Breach forecast AUC {b['metrics']['auc']:.3f}, persistence baseline "
            f"{b['baselines']['persistence_auc']:.3f}; positives not already in breach: {b['metrics']['new_breach_positives']}.",
        ]
    else:
        lines.append("- Simulation: no report found.")
    lines += ["", "## Open audit findings", ""]
    lines += [f"- {f}" for f in _open_findings()] or ["- none recorded"]
    lines += [
        "",
        "## What the validator must not assume",
        "",
        "- All figures are synthetic. No real borrower data was used.",
        "- No entry is validated. Statuses change only with a signed validation report in `docs/validation/`.",
        "- All rule packs are `status: unverified` until a named person checks them against the source.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "docs" / "VALIDATION_PACK.md"
    out.write_text(build(), encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
