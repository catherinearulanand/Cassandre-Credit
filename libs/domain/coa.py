"""Standard chart of accounts (Schedule III, Division II / Ind AS aligned).

Covenant definitions reference these codes only. ``aliases`` drive spread-line mapping
(M13 baseline): labels as printed in Indian financial statements, including common
IGAAP/Ind AS variants. ``sign`` is the natural sign when aggregating to the parent.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

Statement = Literal["BS", "PL", "CF", "MEMO"]


@dataclass(frozen=True)
class CoALine:
    code: str
    label: str
    statement: Statement
    parent: str | None
    sign: int = 1
    aliases: tuple[str, ...] = field(default_factory=tuple)
    is_total: bool = False
    note: str = ""


def _l(
    code: str,
    label: str,
    st: Statement,
    parent: str | None,
    *aliases: str,
    sign: int = 1,
    total: bool = False,
    note: str = "",
) -> CoALine:
    return CoALine(code, label, st, parent, sign, tuple(aliases), total, note)


